test('1単語の地名や地域名には区切りを入れない', () => {
  // 横浜町（青森県）と長野原町（群馬県）は市名・県名で始まるが1単語の町名
  assert.equal(getAreaReading('横浜町'), 'よこはままち');
  assert.equal(getAreaReading('長野原町'), 'ながのはらまち');
  // 地域名は対象外
  assert.equal(getAreaReading('沖縄本島'), 'おきなわほんとう');
  assert.equal(getAreaReading('東京湾内湾'), 'とうきょうわんないわん');
  // 宮城川崎町は県名との区切りだけが入り、町名自体は分割しない
  assert.equal(getAreaReading('宮城川崎町'), 'みやぎ かわさきまち');
});
